import { loadData } from "./src/loader.js";
import { SoccerStore } from "./src/store.js";
const d = loadData();
console.log("matches:", d.matches.length, "dups dropped:", d.duplicatesDropped);
console.log("comp counts:", JSON.stringify(d.competitionCounts));
console.log("seasons:", JSON.stringify(d.competitionSeasons));
const store = new SoccerStore(d);
const st2019 = store.standings("Brasileirão", 2019);
console.log("2019 top5:", st2019.slice(0,5).map(r=>`${r.team} ${r.points}pts (${r.wins}W${r.draws}D${r.losses}L, GF${r.goalsFor} GA${r.goalsAgainst})`));
console.log("2019 teams:", st2019.length, "top played:", st2019[0]?.played);
const st2023 = store.standings("Brasileirão", 2023);
console.log("2023 top5:", st2023.slice(0,5).map(r=>`${r.team} ${r.points}pts (${r.wins}W${r.draws}D${r.losses}L)`));
console.log("2023 teams:", st2023.length);
const fla2019 = store.teamStats("Flamengo", { competition: "Brasileirão", season: 2019 });
console.log("Flamengo 2019:", JSON.stringify(fla2019));
const bw = store.biggestWins({ limit: 3 });
console.log("biggest wins:", bw.map(m=>`${m.date} ${m.homeTeam} ${m.homeGoal}-${m.awayGoal} ${m.awayTeam} (${m.competition})`));
const h2h = store.headToHead("Flamengo", "Fluminense");
console.log("Fla-Flu:", h2h.matches.length, h2h.team1Wins, h2h.team2Wins, h2h.draws);
const extCount = d.matches.filter(m => m.homeShots != null).length;
console.log("matches with extended stats:", extCount);
const serB2023 = store.standings("Brasileirão Série B", 2023);
console.log("Serie B 2023 teams:", serB2023.length, "champ:", serB2023[0]?.team, serB2023[0]?.points);
const st2008 = store.standings("Brasileirão", 2008);
console.log("2008 top3:", st2008.slice(0,3).map(r=>`${r.team} ${r.points}`), "teams:", st2008.length);
